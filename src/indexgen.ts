import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { compareForNext, computeStats, isPickable } from './derive.js';
import { isStale } from './state.js';
import type { Item, Repo } from './types.js';

function line(item: Item, suffix = ''): string {
  const sev = item.meta.sev === undefined ? '' : ` [${item.meta.sev}]`;
  return `- #${item.meta.id}${sev} ${item.meta.title} (${item.meta.kind})${suffix}`;
}

export function renderIndex(repo: Repo, items: readonly Item[]): string {
  const stats = computeStats(repo, items);
  const sorted = [...items].sort((a, b) => a.meta.id - b.meta.id);
  const dir = repo.config.todosDir;
  const out: string[] = [
    '# TODO',
    '',
    '<!-- Generated by workgate. Do not edit; use the "wg" CLI. -->',
    '',
    `Needs you: ${stats.blocked} | Open: ${stats.open} | Total: ${stats.total} | Done: ${stats.byStatus.done} | Dropped: ${stats.byStatus.dropped}`,
    '',
    `Item files live in \`${dir}/\`. Run \`wg list\`, \`wg next\` or \`wg review\` for views.`,
    '',
  ];

  const blocked = sorted.filter((i) => i.meta.status === 'blocked');
  out.push('## Needs you', '');
  if (blocked.length === 0) out.push('Nothing is waiting on you.');
  for (const item of blocked) {
    out.push(line(item));
    out.push(`  needs: ${item.meta.needs ?? ''}`);
  }
  out.push('');

  const active = sorted.filter((i) => i.meta.status === 'active');
  out.push('## Active', '');
  if (active.length === 0) out.push('Nothing is in progress.');
  for (const item of active) {
    const staleNote = isStale(repo, item.meta.id) ? ' - stale' : '';
    out.push(line(item, ` - wt:${item.meta.wt ?? ''}${staleNote}`));
  }
  out.push('');

  const todo = sorted.filter((i) => i.meta.status === 'todo').sort(compareForNext);
  out.push('## Todo', '');
  if (todo.length === 0) out.push('Nothing is waiting to be picked up.');
  for (const item of todo) {
    out.push(line(item, isPickable(item, items) ? '' : ' - waiting on dependencies'));
  }
  out.push('');

  const closed = sorted
    .filter((i) => i.meta.status === 'done' || i.meta.status === 'dropped')
    .sort((a, b) => (b.meta.closed ?? '').localeCompare(a.meta.closed ?? '') || b.meta.id - a.meta.id);
  out.push('## Recently closed', '');
  if (closed.length === 0) out.push('Nothing has been closed yet.');
  for (const item of closed.slice(0, 10)) {
    out.push(line(item, ` - ${item.meta.status} ${item.meta.closed ?? ''}`));
  }
  if (closed.length > 10) out.push('', `${closed.length - 10} older closed items: see \`wg list --all\`.`);
  out.push('');
  return out.join('\n');
}

export function indexPath(repo: Repo): string {
  return join(repo.mainRoot, repo.config.indexFile);
}

export function writeIndex(repo: Repo, items: readonly Item[]): string {
  const file = indexPath(repo);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, renderIndex(repo, items));
  return relative(repo.mainRoot, file);
}
